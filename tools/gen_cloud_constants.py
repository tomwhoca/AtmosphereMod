"""Generate addon/src/cloud_constants.h: the cloud constants (tools/patch_dxil.py cloud_constant_lines, what the
cloud shaders derive from C0..C35 alone) as C++, for the add-on to compute on the CPU and write into the cloud
cbuffer after C0..C35. The shaders then read them instead of computing them in every thread (on RDNA 3 each held
a vector register through the cloud march).

    python tools/gen_cloud_constants.py            # write the header
    python tools/gen_cloud_constants.py --check    # exit 1 if it's out of date

tools/test_cloud_constants.py checks the C++ against patch_dxil.eval_cloud_constants.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import patch_dxil as P  # noqa: E402

OUT = ROOT / "addon" / "src" / "cloud_constants.h"
UNARY = {7: "sat", 12: "std::cos", 13: "std::sin", 21: "std::exp2", 23: "std::log2", 24: "std::sqrt"}
CMP = {"ole": "<=", "olt": "<", "ogt": ">", "oge": ">="}


def ident(name: str) -> str:
    return "v_" + name[1:].replace(".", "_")


def operand(tok: str) -> str:
    tok = tok.strip().rstrip(",")
    if m := re.fullmatch(r"%mod\.C(\d+)", tok):
        return f"C[{m[1]}]"
    if tok.startswith("%"):
        return ident(tok)
    if tok in ("true", "false"):
        return tok
    return float.hex(float(P.literal_value(tok))).replace("0x", "0x", 1) + "f"


def expression(rhs: str) -> tuple[str, str]:
    """(C++ type, expression) for one line's right-hand side."""
    if m := re.match(r"call float @dx\.op\.(unary|binary|tertiary)\.f32\(i32 (\d+), (.*)\)$", rhs):
        op, args = int(m[2]), [operand(a) for a in re.findall(r"float ([^,)]+)", m[3])]
        if m[1] == "unary":
            return "float", f"{UNARY[op]}({args[0]})"
        if m[1] == "binary":
            return "float", f"{'std::fmax' if op == 35 else 'std::fmin'}({args[0]}, {args[1]})"
        return "float", f"{args[0]} * {args[1]} + {args[2]}"
    if m := re.match(r"f(mul|add|sub|div) fast float (\S+), (\S+)$", rhs):
        return "float", f"{operand(m[2])} {dict(mul='*', add='+', sub='-', div='/')[m[1]]} {operand(m[3])}"
    if m := re.match(r"select i1 (\S+), float (\S+), float (\S+)$", rhs):
        return "float", f"{operand(m[1])} ? {operand(m[2])} : {operand(m[3])}"
    if m := re.match(r"fcmp fast (\w+) float (\S+), (\S+)$", rhs):
        return "bool", f"{operand(m[2])} {CMP[m[1]]} {operand(m[3])}"
    if m := re.match(r"(and|or|xor) i1 (\S+), (\S+)$", rhs):
        return "bool", f"{operand(m[2])} {dict(xor='!=', **{'and': '&&', 'or': '||'})[m[1]]} {operand(m[3])}"
    raise SystemExit(f"can't translate: {rhs}")


def header() -> str:
    lines = [P.CONSTANT_DEF.match(line).groups() for line in P.cloud_constant_lines()]
    # every float, and the switches (bools) they need, directly or through others; the rest the shaders compute
    needed, keep = set(), []
    for name, rhs in reversed(lines):
        kind, expr = expression(rhs)
        if kind == "float" or name in needed:
            needed.update(re.findall(r"%[\w.]+", rhs))
            keep.append(f"    const {kind} {ident(name)} = {expr};")
    body = keep[::-1]
    outs = [f"    out[{k}] = {ident(n)};" for k, n in enumerate(P.CLOUD_CONSTANTS)]
    names = ",\n".join(f'    "{n[5:]}"' for n in P.CLOUD_CONSTANTS)
    return f"""// Generated by tools/gen_cloud_constants.py from tools/patch_dxil.py's cloud_constant_lines(): don't edit.
//
// The cloud constants: what the cloud shaders derive from the cloud tunables C0..C35 alone, computed here on the
// CPU and written into the cloud cbuffer after C0..C35 (atmosphere_mod.cpp write_cloud_settings), in this order;
// the shaders read them instead of computing them in every thread.

#pragma once

#include <cmath>
#include <cstdint>

namespace cloud_constants
{{
constexpr uint32_t kTunables = {P.CLOUD_TUNABLES_SIZE // 4};  // C0..C35
constexpr uint32_t kCount = {len(P.CLOUD_CONSTANTS)};
constexpr uint32_t kCbufferBytes = {P.CLOUD_PARAMS_SIZE};  // C0..C35, then the constants, in rows of 4

constexpr const char *kNames[kCount] = {{
{names},
}};

inline float sat(float x)
{{
    return std::fmin(std::fmax(x, 0.0f), 1.0f);
}}

// C: C0..C35 as the shaders get them; out: the kCount constants.
inline void compute(const float *C, float *out)
{{
{chr(10).join(body)}
{chr(10).join(outs)}
}}
}} // namespace cloud_constants
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the header is out of date")
    args = ap.parse_args()
    text = header()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            raise SystemExit(f"{OUT.relative_to(ROOT)} is out of date: run tools/gen_cloud_constants.py")
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(P.CLOUD_CONSTANTS)} constants")


if __name__ == "__main__":
    main()
